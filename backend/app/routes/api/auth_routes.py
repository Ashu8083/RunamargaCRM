# ========================================================================
# API AUTHENTICATION ROUTER
# ========================================================================

router = APIRouter(
    prefix="/auth",
    tags=["API Authentication"],
)


# ========================================================================
# EMPLOYEE IDENTIFICATION
# ========================================================================
#
# POST /android/auth/identify
#
# Content-Type:
#
#     application/json
#
#
# Request:
#
# {
#     "employee_code": "sharathre345@gmail.com"
# }
#
#
# This endpoint:
#
#     1. Checks employees table
#     2. Validates employee status
#     3. Checks employee_face_profiles
#
#
# If face profile EXISTS:
#
#     next_step = FACE_LOGIN
#
#     No temporary token is generated.
#
#
# If face profile DOES NOT EXIST:
#
#     next_step = FACE_ENROLLMENT
#
#     A temporary 5-minute token is generated.
#
#
# Android uses next_step to decide which screen to open.
#
# ========================================================================

@router.post(
    "/identify",
    response_model=EmployeeIdentifyResponse,
)
def identify_employee(
    request: EmployeeIdentifyRequest,
    http_request: Request,
    db: Session = Depends(get_db),
):
    # --------------------------------------------------------------------
    # Get actual client IP.
    #
    # Android does not provide this.
    # --------------------------------------------------------------------

    ip_address = None

    if http_request.client:

        ip_address = http_request.client.host

    # --------------------------------------------------------------------
    # Optional device information.
    #
    # These can be supplied through headers during identification.
    #
    # Example:
    #
    # X-Device-ID: android-device-001
    # X-Device-Type: android
    #
    # --------------------------------------------------------------------

    device_id = http_request.headers.get(
        "X-Device-ID"
    )

    device_type = http_request.headers.get(
        "X-Device-Type"
    )

    try:

        return identify_employee_controller(
            db=db,
            request=request,
            ip_address=ip_address,
            device_id=device_id,
            device_type=device_type,
        )

    except ValueError as exc:

        raise HTTPException(
            status_code=401,
            detail=str(exc),
        )


# ========================================================================
# FIRST-TIME FACE ENROLLMENT
# ========================================================================
#
# POST /android/auth/face-enrollment
#
# Content-Type:
#
#     multipart/form-data
#
#
# Fields:
#
#     temporary_token
#     front_image
#     left_image
#     right_image
#
#
# The employee must provide THREE face captures:
#
#     FRONT
#     LEFT
#     RIGHT
#
#
# This endpoint DOES NOT require a normal access token.
#
# Instead it requires the short-lived:
#
#     face_enrollment
#
# token generated by /identify.
#
#
# Flow:
#
#     temporary_token
#             ↓
#     Validate JWT
#             ↓
#     Check token hash in auth_tokens
#             ↓
#     Check token type
#             ↓
#     Check expiration
#             ↓
#     Check revoked_at
#             ↓
#     Check employee
#             ↓
#     FRONT image validation
#             ↓
#     LEFT image validation
#             ↓
#     RIGHT image validation
#             ↓
#     Generate 3 embeddings
#             ↓
#     Save 3 EmployeeFaceProfile rows
#             ↓
#     Revoke temporary token
#
#
# If ANY image fails:
#
#     Enrollment fails.
#
#     No incomplete face profile should remain.
#
# ========================================================================

@router.post(
    "/face-enrollment",
    response_model=FaceEnrollmentResponse,
)
async def face_enrollment(
    # --------------------------------------------------------------------
    # Temporary 5-minute enrollment token
    # --------------------------------------------------------------------

    temporary_token: str = Form(...),

    # --------------------------------------------------------------------
    # FRONT face image
    # --------------------------------------------------------------------

    front_image: UploadFile = File(...),

    # --------------------------------------------------------------------
    # LEFT face image
    # --------------------------------------------------------------------

    left_image: UploadFile = File(...),

    # --------------------------------------------------------------------
    # RIGHT face image
    # --------------------------------------------------------------------

    right_image: UploadFile = File(...),

    # --------------------------------------------------------------------
    # Database
    # --------------------------------------------------------------------

    db: Session = Depends(get_db),
):

    try:

        return await face_enrollment_controller(
            db=db,
            temporary_token=temporary_token,
            front_image=front_image,
            left_image=left_image,
            right_image=right_image,
        )

    except ValueError as exc:

        raise HTTPException(
            status_code=401,
            detail=str(exc),
        )


# ========================================================================
# FACE LOGIN
# ========================================================================
#
# POST /android/auth/face-login
#
# Content-Type:
#
#     multipart/form-data
#
#
# Fields:
#
#     employee_id
#     image
#     device_id
#     device_type
#     latitude
#     longitude
#
#
# This endpoint is used when the employee ALREADY has a registered
# face profile.
#
#
# The registered profile can contain:
#
#     FRONT
#     LEFT
#     RIGHT
#
#
# The incoming face is compared against all registered embeddings.
#
#
# Flow:
#
#     employee_id
#          +
#        image
#          ↓
#     Employee validation
#          ↓
#     Face validation
#          ↓
#     Generate embedding
#          ↓
#     Load employee face profiles
#          ↓
#     Compare against:
#          FRONT
#          LEFT
#          RIGHT
#          ↓
#        MATCH?
#        /    \
#      YES     NO
#       │       │
#       ▼       ▼
#     Login    401
#       │
#       ▼
#     Access JWT
#       +
#     Refresh JWT
#       │
#       ▼
#     Save refresh session
#       │
#       ▼
#     Set cookies
#
# ========================================================================

@router.post(
    "/face-login",
    response_model=FaceLoginResponse,
)
async def face_login(
    request: Request,

    # --------------------------------------------------------------------
    # Employee ID
    # --------------------------------------------------------------------

    employee_id: int = Form(...),

    # --------------------------------------------------------------------
    # Incoming face image
    # --------------------------------------------------------------------

    image: UploadFile = File(...),

    # --------------------------------------------------------------------
    # Device information
    # --------------------------------------------------------------------

    device_id: str | None = Form(None),

    device_type: str | None = Form(None),

    # --------------------------------------------------------------------
    # Location
    # --------------------------------------------------------------------

    latitude: float | None = Form(None),

    longitude: float | None = Form(None),

    # --------------------------------------------------------------------
    # Database
    # --------------------------------------------------------------------

    db: Session = Depends(get_db),
):

    # --------------------------------------------------------------------
    # Get actual client IP.
    # --------------------------------------------------------------------

    ip_address = None

    if request.client:

        ip_address = request.client.host

    try:

        result = await face_login_controller(
            db=db,
            employee_id=employee_id,
            image=image,
            device_id=device_id,
            device_type=device_type,
            ip_address=ip_address,
            latitude=latitude,
            longitude=longitude,
        )

        # ----------------------------------------------------------------
        # Create JSON response.
        # ----------------------------------------------------------------

        response = JSONResponse(
            content=result.model_dump()
        )

        # ----------------------------------------------------------------
        # ACCESS TOKEN COOKIE
        #
        # Lifetime:
        #
        #     30 minutes
        #
        # Local development:
        #
        #     secure=False
        #
        # Production HTTPS:
        #
        #     secure=True
        # ----------------------------------------------------------------

        response.set_cookie(
            key="access_token",
            value=result.access_token,
            httponly=True,
            secure=False,
            samesite="lax",
            max_age=30 * 60,
        )

        # ----------------------------------------------------------------
        # REFRESH TOKEN COOKIE
        #
        # Lifetime:
        #
        #     7 days
        # ----------------------------------------------------------------

        response.set_cookie(
            key="refresh_token",
            value=result.refresh_token,
            httponly=True,
            secure=False,
            samesite="lax",
            max_age=7 * 24 * 60 * 60,
        )

        return response

    except ValueError as exc:

        raise HTTPException(
            status_code=401,
            detail=str(exc),
        )


# ========================================================================
# REFRESH ACCESS TOKEN
# ========================================================================
#
# POST /android/auth/refresh
#
# The refresh token is read from the HttpOnly cookie.
#
#
# Flow:
#
#     refresh_token cookie
#             ↓
#     Decode JWT
#             ↓
#     Verify type = refresh
#             ↓
#     Hash token
#             ↓
#     Find auth_tokens
#             ↓
#     Check revoked_at
#             ↓
#     Check expiration
#             ↓
#     Check employee
#             ↓
#     Generate new access token
#             ↓
#     Replace access_token cookie
#
# ========================================================================

@router.post(
    "/refresh",
    response_model=RefreshTokenResponse,
)
def refresh_token(
    refresh_token: str | None = Cookie(
        default=None
    ),

    db: Session = Depends(get_db),
):

    # --------------------------------------------------------------------
    # Refresh token must exist.
    # --------------------------------------------------------------------

    if not refresh_token:

        raise HTTPException(
            status_code=401,
            detail="Refresh token required.",
        )

    try:

        result = refresh_token_controller(
            db=db,
            refresh_token=refresh_token,
        )

        # ----------------------------------------------------------------
        # Create response.
        # ----------------------------------------------------------------

        response = JSONResponse(
            content=result.model_dump()
        )

        # ----------------------------------------------------------------
        # Replace access token cookie.
        #
        # New lifetime:
        #
        #     30 minutes
        # ----------------------------------------------------------------

        response.set_cookie(
            key="access_token",
            value=result.access_token,
            httponly=True,
            secure=False,
            samesite="lax",
            max_age=30 * 60,
        )

        return response

    except ValueError as exc:

        raise HTTPException(
            status_code=401,
            detail=str(exc),
        )