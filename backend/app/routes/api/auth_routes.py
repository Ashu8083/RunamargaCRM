# ========================================================================
# EMPLOYEE IDENTIFICATION
# ========================================================================
#
# POST /android/auth/identify
#
# Content-Type:
#
#     application/json
#
#
# Request:
#
# {
#     "employee_code": "sharathre345@gmail.com"
# }
#
#
# This endpoint:
#
#     1. Checks employees table
#     2. Validates employee status
#     3. Checks employee_face_profiles
#
#
# If face profile EXISTS:
#
#     next_step = FACE_LOGIN
#
#     No temporary token is generated.
#
#
# If face profile DOES NOT EXIST:
#
#     next_step = FACE_ENROLLMENT
#
#     A temporary 5-minute token is generated.
#
#
# Android uses next_step to decide which screen to open.
#
# ========================================================================

@router.post(
    "/identify",
    response_model=EmployeeIdentifyResponse,
)
def identify_employee(
    request: EmployeeIdentifyRequest,
    http_request: Request,
    db: Session = Depends(get_db),
):
    # --------------------------------------------------------------------
    # Get actual client IP.
    #
    # Android does not provide this.
    # --------------------------------------------------------------------

    ip_address = None

    if http_request.client:

        ip_address = http_request.client.host

    # --------------------------------------------------------------------
    # Optional device information.
    #
    # These can be supplied through headers during identification.
    #
    # Example:
    #
    # X-Device-ID: android-device-001
    # X-Device-Type: android
    #
    # --------------------------------------------------------------------

    device_id = http_request.headers.get(
        "X-Device-ID"
    )

    device_type = http_request.headers.get(
        "X-Device-Type"
    )

    try:

        return identify_employee_controller(
            db=db,
            request=request,
            ip_address=ip_address,
            device_id=device_id,
            device_type=device_type,
        )

    except ValueError as exc:

        raise HTTPException(
            status_code=401,
            detail={
                "code": "IDENTIFY_FAILED",
                "message": str(exc),
            },
        )


# ========================================================================
# FIRST-TIME FACE ENROLLMENT
# ========================================================================
#
# POST /android/auth/face-enrollment
#
# Content-Type:
#
#     multipart/form-data
#
#
# Fields:
#
#     temporary_token
#     front_image
#     left_image
#     right_image
#
#
# The employee must provide THREE face captures:
#
#     FRONT
#     LEFT
#     RIGHT
#
#
# This endpoint DOES NOT require a normal access token.
#
#Instead it requires the short-lived:
#
#     face_enrollment
#
# token generated by /identify.
#
#
# Flow:
#
#     temporary_token
#             ↓
#     Validate JWT
#             ↓
#     Check token hash in auth_tokens
#             ↓
#     Check token type
#             ↓
#     Check expiration
#             ↓
#     Check revoked_at
#             ↓
#     Check employee
#             ↓
#     FRONT image validation
#             ↓
#     LEFT image validation
#             ↓
#     RIGHT image validation
#             ↓
#     Generate 3 embeddings
#             ↓
#     Save 3 EmployeeFaceProfile rows
#             ↓
#     Revoke temporary token
#
#
# If ANY image fails:
#
#     Enrollment fails.
#
#     No incomplete face profile should remain.
#
# ========================================================================

@router.post(
    "/face-enrollment",
    response_model=FaceEnrollmentResponse,
)
async def face_enrollment(
    # --------------------------------------------------------------------
    # Temporary 5-minute enrollment token
    # --------------------------------------------------------------------

    temporary_token: str = Form(...),

    # --------------------------------------------------------------------
    # FRONT face image
    # --------------------------------------------------------------------

    front_image: UploadFile = File(...),

    # --------------------------------------------------------------------
    # LEFT face image
    # --------------------------------------------------------------------

    left_image: UploadFile = File(...),

    # --------------------------------------------------------------------
    # RIGHT face image
    # --------------------------------------------------------------------

    right_image: UploadFile = File(...),

    # --------------------------------------------------------------------
    # Database
    # --------------------------------------------------------------------

    db: Session = Depends(get_db),
):

    try:

        return await face_enrollment_controller(
            db=db,
            temporary_token=temporary_token,
            front_image=front_image,
            left_image=left_image,
            right_image=right_image,
        )

    except ValueError as exc:

        raise HTTPException(
            status_code=401,
            detail={
                "code": "ENROLLMENT_FAILED",
                "message": str(exc),
            },
        )


# ========================================================================
# FACE LOGIN
# ========================================================================
#
# POST /android/auth/face-login
#
# Content-Type:
#
#     multipart/form-data
#
#
# Fields:
#
#     employee_id
#     image
#     device_id
#     device_type
#     latitude
#     longitude
#
#
# This endpoint is used when the employee ALREADY has a registered
# face profile.
#
#
# The registered profile can contain:
#
#     FRONT
#     LEFT
#     RIGHT
#
#
# The incoming face is compared against all registered embeddings.
#
#
# Flow:
#
#     employee_id
#          +
#        image
#          ↓
#     Employee validation
#          ↓
#     Face validation
#          ↓
#     Generate embedding
#          ↓
#     Load employee face profiles
#          ↓
#     Compare against:
#          FRONT
#          LEFT
#          RIGHT
#          ↓
#        MATCH?
#        /    \
#      YES     NO
#       │       │
#       ▼       ▼
#     Login    401
#       │
#       ▼
#     Access JWT
#       +
#     Refresh JWT
#       │
#       ▼
#     Save refresh session
#       │
#       ▼
#     Set cookies
#
# ========================================================================

@router.post(
    "/face-login",
    response_model=FaceLoginResponse,
)
async def face_login(
    request: Request,

    # --------------------------------------------------------------------
    # Employee ID
    # --------------------------------------------------------------------

    employee_id: int = Form(...),

    # --------------------------------------------------------------------
    # Incoming face image
    # --------------------------------------------------------------------

    image: UploadFile = File(...),

    # --------------------------------------------------------------------
    # Device information
    # --------------------------------------------------------------------

    device_id: str | None = Form(None),

    device_type: str | None = Form(None),

    # --------------------------------------------------------------------
    # Location
    # --------------------------------------------------------------------
    latitude: float | None = Form(None),
    longitude: float | None = Form(None),
    # --------------------------------------------------------------------
    # Database
    # --------------------------------------------------------------------
    db: Session = Depends(get_db),
):

    # --------------------------------------------------------------------
    # Get actual client IP.
    # --------------------------------------------------------------------

    ip_address = None

    if request.client:

        ip_address = request.client.host

    try:

        return await face_login_controller(
            db=db,
            employee_id=employee_id,
            image=image,
            device_id=device_id,
            device_type=device_type,
            ip_address=ip_address,
            latitude=latitude,
            longitude=longitude,
        )

    except ValueError as exc:

        raise HTTPException(
            status_code=401,
            detail={
                "code": "LOGIN_FAILED",
                "message": str(exc),
            },
        )


# ========================================================================
# REFRESH ACCESS TOKEN
# ========================================================================
#
# POST /android/auth/refresh
#
# Android sends the refresh token in the request body (or Authorization header).
# Returns a new access token in the JSON response body.
#
# ========================================================================

@router.post(
    "/refresh",
    response_model=RefreshTokenResponse,
)
def refresh_token(
    request: Request,
    body: RefreshTokenRequest | None = None,
    db: Session = Depends(get_db),
):
    token = None
    if body and body.refresh_token:
        token = body.refresh_token.strip()
    elif request.headers.get("X-Refresh-Token"):
        token = request.headers.get("X-Refresh-Token").strip()
    else:
        auth_header = request.headers.get("Authorization")
        if auth_header and auth_header.startswith("Bearer "):
            token = auth_header.split(" ", 1)[1].strip()
        elif auth_header:
            token = auth_header.strip()

    if not token:
        raise HTTPException(
            status_code=401,
            detail={
                "code": "REFRESH_TOKEN_REQUIRED",
                "message": "Refresh token is required. Please provide it in the request body or X-Refresh-Token header.",
            },
        )

    try:
        return refresh_token_controller(
            db=db,
            refresh_token=token,
        )

    except ValueError as exc:
        error_message = str(exc)
        if "expired" in error_message.lower():
            error_code = "REFRESH_TOKEN_EXPIRED"
        elif "revoked" in error_message.lower():
            error_code = "REFRESH_TOKEN_REVOKED"
        else:
            error_code = "REFRESH_FAILED"

        raise HTTPException(
            status_code=401,
            detail={
                "code": error_code,
                "message": error_message,
            },
        )


# ========================================================================
# LOGOUT
# ========================================================================
#
# POST /android/auth/logout
#
# Android logout endpoint that revokes the active tokens.
#
# Supported token transmission methods from Android:
#     - Authorization Header: Bearer <token>
#     - Header: X-Access-Token / X-Refresh-Token / X-Device-ID
#     - JSON body: LogoutRequest(refresh_token, device_id)
#
# Revocation actions:
#     - Marks refresh tokens in auth_tokens as revoked (revoked_at = now)
#     - Blacklists access token in auth_tokens table
# ========================================================================

@router.post(
    "/logout",
    response_model=LogoutResponse,
    dependencies=[Depends(oauth2_scheme)],
    summary="Logout employee and revoke active tokens",
)
def logout(
    http_request: Request,
    body: LogoutRequest | None = None,
    current_employee: Employee = Depends(get_current_api_employee),
    db: Session = Depends(get_db),
):
    # --------------------------------------------------------------------
    # 1. Resolve access token (Authorization or X-Access-Token header)
    # --------------------------------------------------------------------
        raw_access_token = None

        auth_header = http_request.headers.get("Authorization")
        if auth_header and auth_header.startswith("Bearer "):
            raw_access_token = auth_header.split(" ", 1)[1].strip()
        elif auth_header:
            raw_access_token = auth_header.strip()
        elif http_request.headers.get("X-Access-Token"):
            raw_access_token = http_request.headers.get("X-Access-Token").strip()

        # --------------------------------------------------------------------
        # 2. Resolve refresh token (Body or Header)
        # --------------------------------------------------------------------
        raw_refresh_token = (
            (body.refresh_token if body else None)
            or http_request.headers.get("X-Refresh-Token")
        )

        # --------------------------------------------------------------------
        # 3. Resolve device ID (Body or Header)
        # --------------------------------------------------------------------
        device_id = (
            (body.device_id if body else None)
            or http_request.headers.get("X-Device-ID")
        )

        if not isinstance(raw_access_token, str):
            raw_access_token = None
        if not isinstance(raw_refresh_token, str):
            raw_refresh_token = None
        if not isinstance(device_id, str):
            device_id = None

        # --------------------------------------------------------------------
        # Validate token presence
        # --------------------------------------------------------------------
        if not raw_access_token and not raw_refresh_token:
            raise HTTPException(
                status_code=401,
                detail={
                    "code": "LOGOUT_TOKEN_REQUIRED",
                    "message": "An access token or refresh token is required to logout.",
                },
            )

        try:
            return logout_controller(
                db=db,
                access_token=raw_access_token,
                refresh_token=raw_refresh_token,
                device_id=device_id,
            )

        except ValueError as exc:
            raise HTTPException(
                status_code=401,
                detail={
                    "code": "LOGOUT_FAILED",
                    "message": str(exc),
                },
        )


