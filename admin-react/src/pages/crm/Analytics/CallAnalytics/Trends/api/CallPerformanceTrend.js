const hasValue = (value) => {
    return (
        value !== '' &&
        value !== null &&
        value !== undefined
    )
}


// ============================================================
// FETCH CALL PERFORMANCE TREND
// ============================================================

async function fetchCallPerformanceTrend({
    teamLeadId = '',
    agentId = '',
    rmId = '',
    fromDate = '',
    toDate = '',
} = {}) {
    await new Promise((resolve) => {
        setTimeout(resolve, 300)
    })

    let result = [...DUMMY_CALLS]

    if (hasValue(teamLeadId)) {
        result = result.filter(
            (call) =>
                String(call.teamLeadId) ===
                String(teamLeadId),
        )
    }

    if (hasValue(agentId)) {
        result = result.filter(
            (call) =>
                String(call.agentId) ===
                String(agentId),
        )
    }

    if (hasValue(rmId)) {
        result = result.filter(
            (call) =>
                String(call.rmId) ===
                String(rmId),
        )
    }

    if (hasValue(fromDate)) {
        result = result.filter(
            (call) =>
                call.callDate >= fromDate,
        )
    }

    if (hasValue(toDate)) {
        result = result.filter(
            (call) =>
                call.callDate <= toDate,
        )
    }

    return result
}

export default fetchCallPerformanceTrend